import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, posix, resolve } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

// Enforces docs/DOCUMENTATION_STANDARD.md: control blocks, the document register,
// writing rules for current documents, and every relative link and heading anchor.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(resolve(root, path), 'utf8').replace(/\r\n/g, '\n');

const documents = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' })
  .split(/\r?\n/)
  .filter(path => path && (path.toLowerCase().endsWith('.md') || path.endsWith('/README')))
  .filter(path => existsSync(resolve(root, path)));

// Mirrors are generated by scripts/sync-documentation-mirrors.mjs and checked by docsMirror.test.ts.
const mirrors = new Set(documents.filter(path => !path.startsWith('docs/')).map(source => {
  if (source.startsWith('.github/')) return `docs/github/${source.slice('.github/'.length)}`;
  if (!source.includes('/')) return `docs/repository/${source}`;
  return `docs/${source}`;
}));

const machineParsed = new Set([
  'docs/testing/WEBAPP_A_Z_AB_TESTING_PLAN.md',
  'docs/testing/WEBAPP_A_Z_AB_TESTING.md',
]);
const agentInstructions = path => path === 'frontend/AGENTS.md' || path === 'frontend/CLAUDE.md' ||
  path === 'docs/testing/EKI_Antigravity_Webapp_Testing_Skill.md' || path.startsWith('docs/testing/skills/');
const uncontrolled = path => mirrors.has(path) || machineParsed.has(path) || agentInstructions(path) ||
  path.startsWith('.github/');
const controlled = documents.filter(path => !uncontrolled(path));

const areas = new Set(['GEN', 'REQ', 'ARC', 'ADR', 'API', 'DAT', 'UIX', 'SEC', 'CST', 'OPS', 'HW', 'PKG', 'TST', 'EVD']);
const statuses = new Set(['Current', 'Proposed', 'Historical', 'Superseded']);

function controlBlock(path) {
  const lines = read(path).split('\n');
  const header = lines[2]?.replace(/\s+/g, ' ').trim();
  const separator = lines[3]?.replace(/\s|:/g, '');
  const cells = lines[4]?.split('|').slice(1, -1).map(cell => cell.trim());
  if (!/^# \S/.test(lines[0] ?? '') || lines[1] !== '' ||
    header !== '| Document ID | Version | Status | Last updated |' || separator !== '|---|---|---|---|' ||
    cells?.length !== 4) return null;
  const [id, version, status, updated] = cells;
  return { id, version, status, updated, title: lines[0].slice(2) };
}

/** Removes fenced code blocks and inline code so that examples are not parsed as links or prose. */
function proseOnly(text) {
  return text.replace(/^(```|~~~)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, '').replace(/`[^`\n]*`/g, '');
}

function slug(heading) {
  return heading.trim().toLowerCase()
    .replace(/<[^>]+>/g, '')
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

const anchorCache = new Map();
function anchors(path) {
  if (!anchorCache.has(path)) {
    const text = read(path).replace(/^(```|~~~)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, '');
    const seen = new Map();
    const found = new Set();
    for (const match of text.matchAll(/^#{1,6}\s+(.+?)\s*#*\s*$/gm)) {
      const base = slug(match[1].replace(/`/g, ''));
      const count = seen.get(base) ?? 0;
      seen.set(base, count + 1);
      found.add(count ? `${base}-${count}` : base);
    }
    for (const match of text.matchAll(/<a\s+(?:id|name)="([^"]+)"/g)) found.add(match[1]);
    anchorCache.set(path, found);
  }
  return anchorCache.get(path);
}

function links(path) {
  const text = proseOnly(read(path));
  return [...text.matchAll(/!?\[(?:[^\]\n]|\][^(\n])*\]\(\s*<?([^)\s>]+)>?(?:\s+"[^"]*")?\s*\)/g)].map(match => match[1]);
}

test('controlled documents carry a valid control block', () => {
  const problems = [];
  for (const path of controlled) {
    const block = controlBlock(path);
    if (!block) { problems.push(`${path}: missing or malformed control block`); continue; }
    const [, area] = /^EKI-([A-Z]+)-\d{3}$/.exec(block.id) ?? [];
    if (!areas.has(area)) problems.push(`${path}: invalid document ID ${block.id}`);
    if (!/^\d+\.\d+$/.test(block.version)) problems.push(`${path}: invalid version ${block.version}`);
    if (!statuses.has(block.status)) problems.push(`${path}: invalid status ${block.status}`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(block.updated) || Number.isNaN(Date.parse(block.updated))) {
      problems.push(`${path}: invalid date ${block.updated}`);
    }
  }
  assert.deepEqual(problems, []);
});

test('document IDs are unique and every controlled document is in the register', () => {
  const register = read('docs/README.md');
  const registered = new Map();
  for (const line of register.split('\n')) {
    const id = /^\|\s*(EKI-[A-Z]+-\d{3})\s*\|/.exec(line)?.[1];
    const target = /\]\(([^)#\s]+)/.exec(line)?.[1];
    if (id && target) registered.set(id, posix.normalize(posix.join('docs', target)));
  }
  const problems = [];
  const owners = new Map();
  for (const path of controlled) {
    const block = controlBlock(path);
    if (!block) continue;
    if (owners.has(block.id)) problems.push(`${block.id} used by ${owners.get(block.id)} and ${path}`);
    owners.set(block.id, path);
    if (registered.get(block.id) !== path) problems.push(`${block.id} (${path}) is not registered with that path`);
  }
  for (const [id, path] of registered) if (!owners.has(id)) problems.push(`register lists unknown ${id} (${path})`);
  assert.deepEqual(problems, []);
});

test('no document contains emojis or pictographic symbols', () => {
  // Arrows and legal marks are notation, not decoration.
  const allowed = /[©®™←-⇿]/u;
  const problems = [];
  for (const path of documents) {
    for (const match of read(path).matchAll(/\p{Extended_Pictographic}/gu)) {
      if (!allowed.test(match[0])) problems.push(`${path}: ${JSON.stringify(match[0])}`);
    }
  }
  assert.deepEqual([...new Set(problems)], []);
});

test('current documents follow the writing rules', () => {
  const prohibited = /\b(delve|delves|delving|seamless|seamlessly|cutting-edge|utilize|utilise|utilizes|utilization|game-changer|rest assured|it is important to note|in order to)\b/i;
  const problems = [];
  for (const path of controlled.filter(path => !mirrors.has(path))) {
    const block = controlBlock(path);
    if (!block || block.status === 'Historical') continue;
    const text = read(path);
    text.split('\n').forEach((line, index) => {
      if (/[–—]/.test(line)) problems.push(`${path}:${index + 1}: em or en dash`);
    });
    proseOnly(text).split('\n').forEach(line => {
      const phrase = prohibited.exec(line)?.[0];
      if (phrase) problems.push(`${path}: prohibited phrase "${phrase}"`);
    });
  }
  assert.deepEqual(problems, []);
});

test('relative links and anchors resolve', () => {
  const problems = [];
  const checked = documents.filter(path => !mirrors.has(path) && !machineParsed.has(path) && !agentInstructions(path));
  for (const path of checked) {
    for (const target of links(path)) {
      if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
      const [file, anchor] = target.split('#');
      const destination = file ? posix.normalize(posix.join(posix.dirname(path), decodeURIComponent(file))) : path;
      if (destination.startsWith('..') || !existsSync(resolve(root, destination))) {
        problems.push(`${path}: missing ${target}`);
        continue;
      }
      if (anchor && /\.md$|\/README$/.test(destination) && !anchors(destination).has(anchor.toLowerCase())) {
        problems.push(`${path}: missing anchor ${target}`);
      }
    }
  }
  assert.deepEqual(problems, []);
});

test('the repository root holds only community and entry documents', () => {
  const rootDocuments = documents.filter(path => !path.includes('/')).sort();
  assert.deepEqual(rootDocuments, ['CODE_OF_CONDUCT.md', 'CONTRIBUTING.md', 'README.md', 'SECURITY.md']);
});
